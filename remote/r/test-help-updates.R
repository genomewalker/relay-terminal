source("remote/r/relay-r.R")
project <- tempfile("relay-help-test-")
root <- file.path(project, "relay-results", "test-pane")
dir.create(root, recursive = TRUE)
relay_r_connect(root)
before <- get(".relay_r_identity", .GlobalEnv)
print(help("mean", help_type = "text"))
help <- jsonlite::read_json(file.path(root, "help.json"))
stopifnot(grepl("Arithmetic Mean", help$text), identical(help$session_id, before$session_id))
candidate <- file.path(project, "candidate.R")
file.copy("remote/r/relay-r.R", candidate)
jsonlite::write_json(list(session_id = before$session_id, path = candidate,
  md5 = "incorrect"), file.path(root, "companion-update.json"), auto_unbox = TRUE)
.relay_r_updates$publish()
stopifnot(identical(.relay_r_identity$session_id, before$session_id))
jsonlite::write_json(list(session_id = before$session_id, path = candidate,
  md5 = unname(tools::md5sum(candidate))), file.path(root, "companion-update.json"), auto_unbox = TRUE)
.relay_r_updates$publish()
stopifnot(!identical(.relay_r_identity$session_id, before$session_id))
print(help("sum", help_type = "text"))
help <- jsonlite::read_json(file.path(root, "help.json"))
stopifnot(identical(help$session_id, .relay_r_identity$session_id))
removeTaskCallback(.relay_r_updates$callback)
unlink(project, recursive = TRUE)
cat("Console help and between-command update checks passed\n")

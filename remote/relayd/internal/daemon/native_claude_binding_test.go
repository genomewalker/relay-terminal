func TestNativeClaudePrivateRegistrationGuards(t *testing.T) {
	dir := t.TempDir()
	_ = os.Chmod(dir, 0700)
	path := filepath.Join(dir, "123.json")
	valid := nativeClaudeRegistration{PID: 123, SessionID: "1e292b09-1f1c-49eb-9b3a-85844d9b8cd7", ProcessStart: "expected", Socket: filepath.Join(dir, "peer.sock"), PeerProtocol: 1, Kind: "interactive", Entrypoint: "cli", PIDDomain: nativeClaudePIDDomain()}
	save := func(v nativeClaudeRegistration) {
		data, _ := json.Marshal(v)
		if err := os.WriteFile(path, data, 0600); err != nil {
			t.Fatal(err)
		}
		_ = os.Chmod(path, 0600)
	}
	save(valid)
	if _, _, _, err := readNativeClaudeRegistration(path, 123, "expected"); err != nil {
		t.Fatal(err)
	}
	_ = os.Chmod(path, 0644)
	if _, _, _, err := readNativeClaudeRegistration(path, 123, "expected"); err != nil {
		t.Fatal("owned readable SDK metadata rejected", err)
	}
	_ = os.Chmod(path, 0600)
	for name, change := range map[string]func(*nativeClaudeRegistration){"pid": func(v *nativeClaudeRegistration) { v.PID = 124 }, "start": func(v *nativeClaudeRegistration) { v.ProcessStart = "stale" }, "session": func(v *nativeClaudeRegistration) { v.SessionID = "../bad" }, "socket": func(v *nativeClaudeRegistration) { v.Socket = "relative.sock" }, "protocol": func(v *nativeClaudeRegistration) { v.PeerProtocol = 2 }, "kind": func(v *nativeClaudeRegistration) { v.Kind = "headless" }, "entrypoint": func(v *nativeClaudeRegistration) { v.Entrypoint = "sdk" }, "domain": func(v *nativeClaudeRegistration) { v.PIDDomain = "other" }, "proxy": func(v *nativeClaudeRegistration) { v.RelayProxy = true }} {
		t.Run(name, func(t *testing.T) {
			v := valid
			change(&v)
			save(v)
			if _, _, _, err := readNativeClaudeRegistration(path, 123, "expected"); err == nil {
				t.Fatal("unsafe registration accepted")
			}
		})
	}
	save(valid)
	_ = os.Chmod(path, 0664)
	if _, _, _, err := readNativeClaudeRegistration(path, 123, "expected"); err == nil {
		t.Fatal("writable registration accepted")
	}
	_ = os.Chmod(path, 0600)
	if err := os.Remove(path); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(filepath.Join(dir, "elsewhere"), path); err != nil {
		t.Fatal(err)
	}
	if _, _, _, err := readNativeClaudeRegistration(path, 123, "expected"); err == nil {
		t.Fatal("symlink accepted")
	}
	_ = os.Remove(path)
	if err := os.WriteFile(path, []byte(strings.Repeat(" ", 65537)), 0600); err != nil {
		t.Fatal(err)
	}
	if _, _, _, err := readNativeClaudeRegistration(path, 123, "expected"); err == nil {
		t.Fatal("oversized registration accepted")
	}
}
func TestNativeClaudeSocketOwnershipAndTranscriptBounds(t *testing.T) {
	dir, err := os.MkdirTemp("", "relay-claude-socket-")
	if err != nil {
		t.Fatal(err)
	}
	defer os.RemoveAll(dir)
	socket := filepath.Join(dir, "peer.sock")
	listener, err := net.Listen("unix", socket)
	if err != nil {
		t.Fatal(err)
	}
	defer listener.Close()
	_ = os.Chmod(socket, 0600)
	if _, err := nativeClaudeSocketIdentity(socket); err != nil {
		t.Fatal(err)
	}
	_ = os.Chmod(socket, 0666)
	if _, err := nativeClaudeSocketIdentity(socket); err == nil {
		t.Fatal("writable socket accepted")
	}
	home := t.TempDir()
	if path, err := nativeClaudeTranscript(filepath.Join(home, ".claude"), "1e292b09-1f1c-49eb-9b3a-85844d9b8cd7"); err != nil || path != "" {
		t.Fatal("missing initial transcript not supported")
	}
	for _, name := range []string{"one", "two"} {
		folder := filepath.Join(home, ".claude", "projects", name)
		if err := os.MkdirAll(folder, 0700); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(folder, "1e292b09-1f1c-49eb-9b3a-85844d9b8cd7.jsonl"), []byte("{}\n"), 0600); err != nil {
			t.Fatal(err)
		}
	}
	if _, err := nativeClaudeTranscript(filepath.Join(home, ".claude"), "1e292b09-1f1c-49eb-9b3a-85844d9b8cd7"); err == nil {
		t.Fatal("ambiguous transcript accepted")
	}
}

func TestNativeClaudeLinuxPIDDomainMatchesSDKMachineID(t *testing.T) {
	// Literal SDK publication observed from Claude2.1.295, rather than a fixture
	// generated by the reader itself. Boot UUID is a different identity.
	got := nativeClaudeLinuxPIDDomain("acddeb811e0b4e86aab6d5ab72e98944\n", "pid:[4026531836]")
	want := "linux:acddeb811e0b4e86aab6d5ab72e98944:pid:[4026531836]"
	if got != want {
		t.Fatalf("SDK domain mismatch: %q", got)
	}
	other := nativeClaudeLinuxPIDDomain("acddeb811e0b4e86aab6d5ab72e98944", "pid:[4026531837]")
	if other == got {
		t.Fatal("PID namespace was ignored")
	}
	for _, tc := range [][2]string{
		{"", "pid:[4026531836]"}, {"1f226807-dc07-4039-90bd-3685f31bf47e", "pid:[4026531836]"},
		{"xyz", "pid:[4026531836]"}, {"acddeb811e0b4e86aab6d5ab72e98944", ""},
		{"acddeb811e0b4e86aab6d5ab72e98944", "pid:[123"}, {"acddeb811e0b4e86aab6d5ab72e98944", "mnt:[123]"},
	} {
		if domain := nativeClaudeLinuxPIDDomain(tc[0], tc[1]); domain != "" {
			t.Fatalf("malformed identity accepted: %q", domain)
		}
	}
}
